// Regenerate the marker picker data and icon assets from the shipped XMind.
//
//   node scripts/build-marker-data.mjs
//
// Facts are read from the official renderer bundle and app.asar; the generated
// files are deliberately machine-owned, do not hand-edit them.
//   src/lib/marker-data.ts
//   public/markers/<group>/<marker>.svg
//   public/markers/ui/{marker,sticker,illustration}.svg
import { readFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import vm from 'node:vm';

const ROOT = resolve(import.meta.dirname, '..');
const RENDERER = resolve(ROOT, 'research/asar-src/renderer/2907.js');
const ASAR = process.env.XMIND_ASAR
  || 'C:/Users/DM/AppData/Local/Programs/Xmind/resources/app.asar';
const OUT_TS = resolve(ROOT, 'src/lib/marker-data.ts');
const OUT_DIR = resolve(ROOT, 'public/markers');

const src = readFileSync(RENDERER, 'utf8');

function literalString(re) {
  const match = src.match(re);
  if (!match) throw new Error(`marker bundle pattern missing: ${re}`);
  return vm.runInNewContext(`'${match[1]}'`);
}

function objectBetween(startRe, endText) {
  const match = src.match(startRe);
  if (!match) throw new Error(`marker object pattern missing: ${startRe}`);
  const start = match.index + match[0].length;
  const end = src.indexOf(endText, start);
  if (end < 0) throw new Error(`marker object end missing: ${endText}`);
  return vm.runInNewContext(`(${src.slice(start, end).trim()})`);
}

const registry = JSON.parse(literalString(/const hA=JSON\.parse\('((?:[^'\\]|\\.)*)'\)/));
const groupNames = objectBetween(/const OA=/, ',RA=');
const markerNames = objectBetween(/RA=/, ';var _A=');
const orderMatch = src.match(/const mA=\[([^\]]+)\]/);
if (!orderMatch) throw new Error('marker group order missing');
const order = [...orderMatch[1].matchAll(/pA\.(\w+)/g)].map((m) => m[1]);

// Official App.asar layout: 4-byte pickle size, JSON header, then file bytes.
const asar = readFileSync(ASAR);
const pickleSize = asar.readUInt32LE(4);
const jsonSize = asar.readUInt32LE(12);
const header = JSON.parse(asar.subarray(16, 16 + jsonSize).toString('utf8'));
const dataBase = 8 + pickleSize;
function* walk(node, prefix = '') {
  for (const [name, entry] of Object.entries(node.files ?? {})) {
    const path = prefix ? `${prefix}/${name}` : name;
    if (entry.files) yield* walk(entry, path);
    else yield [path, entry];
  }
}
const files = new Map([...walk(header)]);

const groups = [];
let markerCount = 0;
for (const groupId of order) {
  const group = registry[groupId];
  if (!group || group.hidden) continue;
  const items = [];
  for (const marker of group.markers) {
    if (marker.hidden) continue;
    const relative = marker.resource.replace(/\\/g, '/');
    const asarPath = `static/snowbird/resource/${relative}`;
    const entry = files.get(asarPath);
    if (!entry) throw new Error(`marker asset missing in asar: ${asarPath}`);
    const bytes = asar.subarray(dataBase + Number(entry.offset), dataBase + Number(entry.offset) + Number(entry.size));
    const outPath = join(OUT_DIR, relative.replace(/^markers\//, ''));
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, bytes);
    items.push({
      id: marker.markerId,
      label: markerNames[marker.markerId]?.['en-US'] ?? marker.markerId,
      icon: `/markers/${relative.replace(/^markers\//, '')}`,
    });
    markerCount += 1;
  }
  groups.push({
    id: groupId,
    title: groupNames[groupId]?.['zh-CN'] ?? groupId,
    items,
  });
}

const generated = `// GENERATED by scripts/build-marker-data.mjs — do not edit by hand.\n`
  + `export interface MarkerDataItem {\n  id: string;\n  label: string;\n  icon: string;\n}\n\n`
  + `export interface MarkerDataGroup {\n  id: string;\n  title: string;\n  items: MarkerDataItem[];\n}\n\n`
  + `export const MARKER_DATA: MarkerDataGroup[] = ${JSON.stringify(groups, null, 2)};\n\n`
  + `export const MARKER_UI = {\n`
  + `  marker: '/markers/ui/marker.svg',\n`
  + `  sticker: '/markers/ui/sticker.svg',\n`
  + `  illustration: '/markers/ui/illustration.svg',\n`
  + `} as const;\n`;
mkdirSync(dirname(OUT_TS), { recursive: true });
writeFileSync(OUT_TS, generated);

// The official icon-module panel has three 16px tabs above the marker grid.
// Extract the same SVGs from app.asar so the header is not hand-drawn.
const uiIcons = ['marker', 'sticker', 'illustration'];
for (const name of uiIcons) {
  const asarPath = `static/assets/images/icon-module/${name}.svg`;
  const entry = files.get(asarPath);
  if (!entry) throw new Error(`icon-module asset missing in asar: ${asarPath}`);
  const bytes = asar.subarray(dataBase + Number(entry.offset), dataBase + Number(entry.offset) + Number(entry.size));
  const outPath = join(OUT_DIR, 'ui', `${name}.svg`);
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, bytes);
}
console.log(`${groups.length} groups, ${markerCount} markers: ${OUT_TS}`);
if (!existsSync(OUT_TS)) throw new Error('marker data write failed');
