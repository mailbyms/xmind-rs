// Build src/inspector/skeletons.ts from the extracted preset table plus the
// thumbnails captured out of the shipped panel.
// Usage: node scripts/build-skeleton-data.mjs
import { copyFileSync, existsSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';

const presets = JSON.parse(readFileSync('research/skeleton-presets.json', 'utf8'));
const cards = JSON.parse(readFileSync('research/skeleton-cards.json', 'utf8'));

/** Thumbnails keep ASCII names so neither Vite nor the bundler has to deal
 *  with percent-encoded paths on disk. */
function asciiName(file, index) {
  const base = file.replace(/-\d+\.svg$/, '');
  const slug = { 思维导图: 'mind-map', 逻辑图: 'logic-chart', 括号图: 'brace-map', 组织结构图: 'org-chart', 树形图: 'tree-chart', 时间轴: 'timeline', 鱼骨图: 'fishbone', 树型表格: 'tree-table', 矩阵图: 'matrix' }[base];
  return `${slug}-${String(index).padStart(2, '0')}.svg`;
}

const GROUP_ORDER = [
  ['Mind Map', '思维导图'],
  ['Logic Chart', '逻辑图'],
  ['Brace Map', '括号图'],
  ['Org Chart', '组织结构图'],
  ['Tree Chart', '树形图'],
  ['Timeline', '时间轴'],
  ['Fishbone', '鱼骨图'],
  ['Tree Table', '树型表格'],
  ['Matrix', '矩阵图'],
];

/** Shipped central-topic class -> the structure enum we can actually lay out. */
const STRUCTURE = {
  'org.xmind.ui.map.clockwise': 'clockwise',
  'org.xmind.ui.map.anticlockwise': 'anticlockwise',
  'org.xmind.ui.map.unbalanced': 'balanced',
  'org.xmind.ui.map': 'balanced',
  'org.xmind.ui.logic.right': 'logicRight',
  'org.xmind.ui.logic.left': 'logicLeft',
  'org.xmind.ui.brace.right': 'braceRight',
  'org.xmind.ui.brace.left': 'braceLeft',
  'org.xmind.ui.org-chart.down': 'orgDown',
  'org.xmind.ui.org-chart.up': 'orgUp',
  'org.xmind.ui.tree.right': 'treeRight',
  'org.xmind.ui.tree.left': 'treeLeft',
  'org.xmind.ui.timeline.horizontal': 'timelineHorizontal',
  'org.xmind.ui.timeline.vertical': 'timeline',
  'org.xmind.ui.timeline.sided.horizontal': 'timelineHorizontal',
  'org.xmind.ui.timeline.through.vertical': 'timeline',
  'org.xmind.ui.timeline.through.vertical': 'timeline',
  'org.xmind.ui.fishbone.leftHeaded': 'fishboneLeft',
  'org.xmind.ui.fishbone.rightHeaded': 'fishboneRight',
  'org.xmind.ui.treetable': 'treeTable',
  'org.xmind.ui.treetable.toptitle': 'treeTable',
  'org.xmind.ui.spreadsheet': 'matrix',
  'org.xmind.ui.spreadsheet.column': 'matrix',
};

const rows = [];
let cursor = 0;
for (const [group, title] of GROUP_ORDER) {
  const mine = presets.filter((p) => p.group === group);
  mine.forEach((preset, index) => {
    const card = cards[cursor++];
    if (!card) throw new Error(`missing thumbnail for ${group}#${index}`);
    const target = asciiName(card.file, index);
    const from = `public/tiles/skeletons/${card.file}`;
    if (target !== card.file && existsSync(from)) {
      copyFileSync(from, `public/tiles/skeletons/${target}`);
      unlinkSync(from);
    }
    const structure = STRUCTURE[preset.central];
    if (!structure) throw new Error(`unmapped structure ${preset.central}`);
    rows.push({
      id: preset.id,
      group,
      title: `${title} ${index + 1}`,
      thumb: `/tiles/skeletons/${target}`,
      structure,
      handDrawn: preset.handDrawn,
      shape: preset.centralShape,
      mainShape: preset.mainShape ?? preset.centralShape,
      line: preset.mainLine ?? preset.centralLine,
      centralLine: preset.centralLine,
      pattern: preset.linePattern ?? 'solid',
      fill: preset.fillPattern ?? 'solid',
      central: preset.central,
      main: preset.main,
      centralWidth: preset.centralWidth ?? null,
      mainWidth: preset.mainWidth ?? null,
      subLine: preset.subLine ?? null,
      subShape: preset.subShape ?? null,
      subPattern: preset.subPattern ?? null,
      subWidth: preset.subWidth ?? null,
      subFill: preset.subFill ?? preset.fillPattern ?? 'solid',
      tapered: preset.tapered ?? null,
    });
  });
}

const ts = `// Generated by scripts/build-skeleton-data.mjs — do not edit by hand.
// The shipped 骨架 library: 9 groups / 43 presets, in the order the original
// panel lists them. Each preset is a full style snapshot (structure + topic
// shapes + branch line), not just a layout switch.
import type { Structure } from '../lib/types';

export interface SkeletonPreset {
  id: string;
  group: string;
  /** Accessible name; the original cards carry no visible caption. */
  title: string;
  /** 106x65 thumbnail captured from the shipped renderer. */
  thumb: string;
  structure: Structure;
  handDrawn: boolean;
  /** Central topic \`shape-class\` short name. */
  shape: string;
  /** First-level topic \`shape-class\` short name. */
  mainShape: string;
  /** Branch \`line-class\` short name (first-level topic). */
  line: string;
  /** Central topic \`line-class\` — the original stores it per preset too. */
  centralLine: string;
  /** \`line-pattern\` (\`solid\` / \`handdrawn-solid\` / …). */
  pattern: string;
  /** \`fill-pattern\` of the preset theme. */
  fill: string;
  /** Third-layer (subTopic) style: every connector below level 1. */
  subLine: string | null;
  subShape: string | null;
  subPattern: string | null;
  subWidth: string | null;
  subFill: string | null;
  /** \`line-width\` of the central / main layers, e.g. \`3pt\` / \`2pt\`. */
  centralWidth: string | null;
  mainWidth: string | null;
  /** \`map/properties/line-tapered\`: none | normal | tapered. */
  tapered: string | null;
  /** Exact \`org.xmind.ui.*\` classes stored in the sheet extension. */
  central: string;
  main: string | null;
}

export interface SkeletonGroup {
  id: string;
  title: string;
  items: SkeletonPreset[];
}

export const SKELETON_GROUPS: SkeletonGroup[] = ${JSON.stringify(
  GROUP_ORDER.map(([group, title]) => ({
    id: group,
    title,
    items: rows
      .filter((r) => r.group === group)
      .map(({ id, group: g, title: t, thumb, structure, handDrawn, shape, mainShape, line, centralLine, pattern, fill, central, main,
        subLine, subShape, subPattern, subWidth, subFill, centralWidth, mainWidth, tapered }) => ({
        id, group: g, title: t, thumb, structure, handDrawn, shape, mainShape, line, centralLine, pattern, fill, central, main,
        subLine, subShape, subPattern, subWidth, subFill, centralWidth, mainWidth, tapered,
      })),
  })),
  null,
  2,
)};

export const ALL_SKELETONS: SkeletonPreset[] = SKELETON_GROUPS.flatMap((g) => g.items);

/** The preset whose style snapshot is closest to \`structure\` — used to show
 *  the current selection when the sheet was not created from a preset. */
export function presetForStructure(structure: Structure | undefined): SkeletonPreset | undefined {
  if (!structure) return undefined;
  return ALL_SKELETONS.find((p) => p.structure === structure && !p.handDrawn)
    ?? ALL_SKELETONS.find((p) => p.structure === structure);
}
`;

writeFileSync('src/inspector/skeletons.ts', ts);
console.log(`wrote src/inspector/skeletons.ts — ${rows.length} presets in ${SKELETON_GROUPS_PLACEHOLDER()}`);
function SKELETON_GROUPS_PLACEHOLDER() {
  return `${GROUP_ORDER.length} groups`;
}
